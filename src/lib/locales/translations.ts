export function resolveLocale(candidate?: string): string {
  if (candidate && candidate !== 'auto') {
    const lang = candidate.toLowerCase().split('-')[0];
    if (SUPPORTED_LANGUAGES.some((item) => item.code === lang)) {
      return lang;
    }
  }

  if (typeof document !== 'undefined' && document.documentElement?.lang) {
    const docLang = document.documentElement.lang.toLowerCase().split('-')[0];
    if (SUPPORTED_LANGUAGES.some((item) => item.code === docLang)) {
      return docLang;
    }
  }

  if (typeof navigator !== 'undefined' && navigator.language) {
    const navLang = navigator.language.toLowerCase().split('-')[0];
    if (SUPPORTED_LANGUAGES.some((item) => item.code === navLang)) {
      return navLang;
    }
  }

  return 'en';
}

export function getLocaleDirection(locale: string): 'ltr' | 'rtl' {
  const lang = locale.toLowerCase().split('-')[0];
  const found = SUPPORTED_LANGUAGES.find((item) => item.code === lang);
  return found?.direction || 'ltr';
}

export function getTranslation(
  locale: string = 'en',
  key: LocaleKey,
  params?: Record<string, string | number>,
): string {
  const lang = locale.toLowerCase().split('-')[0];
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  let text = dict[key] || TRANSLATIONS['en'][key] || key;

  if (params) {
    for (const [paramKey, value] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(value));
    }
  }

  return text;
}

export function formatDate(
  dateValue: string | Date | undefined,
  locale: string = 'en',
  options: Intl.DateTimeFormatOptions = {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  },
): string {
  if (!dateValue) return '';
  try {
    const date = typeof dateValue === 'string' ? new Date(dateValue) : dateValue;
    if (isNaN(date.getTime())) return '';
    return new Intl.DateTimeFormat(locale, options).format(date);
  } catch {
    return new Date(dateValue).toLocaleDateString();
  }
}
